//! DeepSeekHashV1: SHA3-256 padding/rate, with Keccak-p[1600,23].
//! Protocol reference: shaohuahuawww/deepseek-pow (MIT).
use base64::{Engine, engine::general_purpose::STANDARD};
use serde::Deserialize;
use serde_json::json;
use std::{
    fmt::Write,
    sync::{
        Arc,
        atomic::{AtomicBool, Ordering},
    },
    time::{Duration, Instant},
};

#[derive(Deserialize)]
pub struct Challenge {
    algorithm: String,
    challenge: String,
    salt: String,
    expire_at: u64,
    difficulty: u64,
    signature: String,
    #[serde(default = "completion_path")]
    target_path: String,
}

fn completion_path() -> String {
    "/api/v0/chat/completion".into()
}

