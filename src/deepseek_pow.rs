fn hash(input: &[u8]) -> [u8; 32] {
    let mut state = [0u64; 25];
    let (chunks, remaining) = input.as_chunks::<136>();
    let absorb = |state: &mut [u64; 25], block: &[u8]| {
        for (lane, bytes) in state.iter_mut().zip(block.as_chunks::<8>().0) {
            *lane ^= u64::from_le_bytes(*bytes);
        }
        keccak::p1600(state, 23);
    };
    for chunk in chunks {
        absorb(&mut state, chunk);
    }
    let mut final_block = [0; 136];
    final_block[..remaining.len()].copy_from_slice(remaining);
    final_block[remaining.len()] = 0x06;
    final_block[135] |= 0x80;
    absorb(&mut state, &final_block);
    let mut output = [0; 32];
    for (bytes, lane) in output.as_chunks_mut::<8>().0.iter_mut().zip(state) {
        bytes.copy_from_slice(&lane.to_le_bytes());
    }
    output
}

fn solve(challenge: Challenge, cancelled: &AtomicBool) -> Result<String, String> {
    if challenge.algorithm != "DeepSeekHashV1"
        || challenge.challenge.len() != 64
        || challenge.salt.len() > 4096
        || challenge.target_path != "/api/v0/chat/completion"
    {
        return Err("不支持的 DeepSeek PoW 协议".into());
    }
    let mut target = [0; 32];
    for (byte, pair) in target
        .iter_mut()
        .zip(challenge.challenge.as_bytes().as_chunks::<2>().0)
    {
        let text = std::str::from_utf8(pair).map_err(|_| "无效 PoW challenge")?;
        *byte = u8::from_str_radix(text, 16).map_err(|_| "无效 PoW challenge")?;
    }
    let prefix = format!("{}_{}_", challenge.salt, challenge.expire_at);
    let mut input = prefix.clone();
    let start = Instant::now();
    for nonce in 0..challenge.difficulty.min(50_000_000) {
        if nonce % 1024 == 0
            && (cancelled.load(Ordering::Relaxed) || start.elapsed() > Duration::from_secs(30))
        {
            return Err("DeepSeek PoW 已取消或超时".into());
        }
        input.truncate(prefix.len());
        write!(&mut input, "{nonce}").map_err(|_| "PoW 编码失败")?;
        if hash(input.as_bytes()) == target {
            return Ok(STANDARD.encode(json!({"algorithm":challenge.algorithm,"challenge":challenge.challenge,"salt":challenge.salt,"answer":nonce,"signature":challenge.signature,"target_path":challenge.target_path}).to_string()));
        }
    }
    Err("DeepSeek PoW 未求得结果，接口可能已更新".into())
}

struct Cancel(Arc<AtomicBool>);
impl Drop for Cancel {
    fn drop(&mut self) {
        self.0.store(true, Ordering::Relaxed);
    }
}

pub async fn header(challenge: Challenge) -> Result<String, String> {
    let flag = Arc::new(AtomicBool::new(false));
    let _cancel = Cancel(flag.clone());
    tokio::task::spawn_blocking(move || solve(challenge, &flag))
        .await
        .map_err(|_| "PoW 工作线程失败")?
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn matches_independent_reference_across_multiple_absorb_blocks() {
        let actual = hash(&[0; 272])
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect::<String>();
        assert_eq!(
            actual,
            "5947cfc2b20a1108c96b3d2b229a7f12871296c83e5e7f38a202df79e0c6138a"
        );
    }
    #[tokio::test]
    async fn solves_a_bounded_challenge_and_encodes_its_proof() {
        let target = hash(b"test_2000000000_7")
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect::<String>();
        let challenge = Challenge {
            algorithm: "DeepSeekHashV1".into(),
            challenge: target,
            salt: "test".into(),
            expire_at: 2000000000,
            difficulty: 20,
            signature: "test-signature".into(),
            target_path: "/api/v0/chat/completion".into(),
        };
        let result = header(challenge).await.unwrap();
        let value: serde_json::Value =
            serde_json::from_slice(&STANDARD.decode(result).unwrap()).unwrap();
        assert_eq!(value["answer"], 7);
        assert_eq!(value["signature"], "test-signature");
    }
    #[test]
    fn rejects_other_algorithms_before_spending_cpu() {
        let challenge: Challenge = serde_json::from_value(json!({"algorithm":"unknown","challenge":"00".repeat(32),"salt":"test","expire_at":1,"difficulty":100000000,"signature":"x","target_path":"/api/v0/chat/completion"})).unwrap();
        assert!(solve(challenge, &AtomicBool::new(false)).is_err());
    }
}
